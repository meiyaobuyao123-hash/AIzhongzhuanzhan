  function getLang() {
    let saved = localStorage.getItem('prism_lang');
    if (saved && SUPPORTED.includes(saved)) return saved;
    return DEFAULT_LANG;
  }

  function setLang(lang) {
    if (!SUPPORTED.includes(lang)) lang = DEFAULT_LANG;
    localStorage.setItem('prism_lang', lang);
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
    location.reload();
  }

  function t(key, vars) {
    const lang = window.LANG || getLang();
    const entry = DICT[key];
    if (!entry) {
      if (typeof console !== 'undefined' && console.warn) {
        console.warn('[i18n] missing key:', key);
      }
      return key;
    }
    let s = entry[lang] || entry[DEFAULT_LANG] || key;
    if (vars && typeof s === 'string') {
      Object.keys(vars).forEach(k => {
        s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
      });
    }
    return s;
  }

  // Apply data-i18n attributes on DOMContentLoaded (for static HTML pages).
  function applyDataI18n() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      el.innerHTML = t(key);
    });
    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
      // format: data-i18n-attr="placeholder:auth.password_hint;title:nav.lang_label"
      const spec = el.getAttribute('data-i18n-attr');
      spec.split(';').forEach(pair => {
        const [attr, key] = pair.split(':').map(s => s.trim());
        if (attr && key) el.setAttribute(attr, t(key));
      });
    });
    // <title> via data-i18n-title="meta.title.home"
    const titleEl = document.querySelector('title[data-i18n]');
    if (titleEl) document.title = t(titleEl.getAttribute('data-i18n'));
  }

  // Initialize
  const initialLang = getLang();
  window.LANG = initialLang;
  document.documentElement.lang = initialLang === 'zh' ? 'zh-CN' : initialLang;

  // Expose
  window.t = t;
  window.setLang = setLang;
  window.getLang = getLang;
  window.PRISM_I18N_SUPPORTED = SUPPORTED;
  window.PRISM_I18N_DICT = DICT;

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyDataI18n);
  } else {
    applyDataI18n();
  }
